def run_self_test() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        write_fixture(root)
        check_release_consistency(root)

        formula = root / "distribution" / "homebrew" / "turbo-lang.rb"
        formula_clean = formula.read_text(encoding="utf-8")
        marker_comment = f"# {HOMEBREW_TEMPLATE_MARKER}; these shas are placeholders.\n"

        def zero_shas(text: str) -> str:
            return re.sub(r'sha256 "[0-9a-f]{64}"', f'sha256 "{PLACEHOLDER_SHA256}"', text)

        # Placeholder (all-zero) shas with no template marker must fail — this is
        # the BL-8 bug: a formula that looks real but carries fake checksums.
        formula.write_text(zero_shas(formula_clean), encoding="utf-8")
        try:
            check_release_consistency(root)
        except CheckFailure as exc:
            require("non-authoritative template" in str(exc), f"self-test expected placeholder-sha failure, got: {exc}")
        else:
            raise CheckFailure("self-test expected placeholder shas without a template marker to fail")

        # Template marker present but real-looking (non-placeholder) shas must fail.
        formula.write_text(marker_comment + formula_clean, encoding="utf-8")
        try:
            check_release_consistency(root)
        except CheckFailure as exc:
            require("non-placeholder" in str(exc), f"self-test expected marked-template real-sha failure, got: {exc}")
        else:
            raise CheckFailure("self-test expected a marked template with real shas to fail")

        # A marked template with the all-zero sentinel shas is the honest state — must pass.
        formula.write_text(zero_shas(marker_comment + formula_clean), encoding="utf-8")
        check_release_consistency(root)

        # Restore the clean fixture formula for the remaining mutations below.
        formula.write_text(formula_clean, encoding="utf-8")

        formula.write_text(formula.read_text(encoding="utf-8").replace("turbo-lsp", "missing-lsp", 1), encoding="utf-8")
        try:
            check_release_consistency(root)
        except CheckFailure as exc:
            require("turbo-lsp" in str(exc), f"self-test expected turbo-lsp failure, got: {exc}")
        else:
            raise CheckFailure("self-test expected mutated Homebrew formula to fail")

        workspace_manifest = root / "turbo" / "Cargo.toml"
        workspace_manifest.write_text(
            workspace_manifest.read_text(encoding="utf-8").replace('readme = "../README.md"', 'readme = "README.md"'),
            encoding="utf-8",
        )
        try:
            check_release_consistency(root)
        except CheckFailure as exc:
            require("[workspace.package] readme" in str(exc), f"self-test expected workspace readme failure, got: {exc}")
        else:
            raise CheckFailure("self-test expected wrong workspace readme metadata to fail")
        workspace_manifest.write_text(
            workspace_manifest.read_text(encoding="utf-8").replace('readme = "README.md"', 'readme = "../README.md"'),
            encoding="utf-8",
        )

        ast_manifest = root / "turbo" / "crates" / "turbo-ast" / "Cargo.toml"
        ast_manifest.write_text(
            ast_manifest.read_text(encoding="utf-8").replace("readme.workspace = true\n", ""),
            encoding="utf-8",
        )
        try:
            check_release_consistency(root)
        except CheckFailure as exc:
            require("workspace readme metadata" in str(exc), f"self-test expected readme metadata failure, got: {exc}")
        else:
            raise CheckFailure("self-test expected missing crate readme metadata to fail")

    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        write_fixture(root)
        subprocess.run(["git", "-C", str(root), "init"], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        write(root / "turbo" / "benchmarks" / "c" / "fib", "generated binary placeholder\n")
        write(root / "turbo" / "benchmarks" / "c" / "fib.c", "int main(void) { return 0; }\n")
        write(root / "turbo" / "benchmarks" / "js" / "fib.js", "console.log(1)\n")
        write(root / "turbo" / "benchmarks" / "go" / "fib", "generated binary placeholder\n")
        subprocess.run(
            [
                "git",
                "-C",
                str(root),
                "add",
                "turbo/benchmarks/c/fib",
                "turbo/benchmarks/c/fib.c",
                "turbo/benchmarks/js/fib.js",
                "turbo/benchmarks/go/fib",
            ],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        try:
            check_release_consistency(root)
        except CheckFailure as exc:
            require("tracked benchmark generated artifacts" in str(exc), f"self-test expected benchmark artifact failure, got: {exc}")
        else:
            raise CheckFailure("self-test expected tracked benchmark artifact to fail")

        subprocess.run(
            ["git", "-C", str(root), "rm", "--cached", "turbo/benchmarks/c/fib", "turbo/benchmarks/go/fib"],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        check_release_consistency(root)

    print("self-test: release consistency fixture checks passed")
    return 0


def main() -> int:
    if len(sys.argv) == 2 and sys.argv[1] == "--self-test":
        try:
            return run_self_test()
        except CheckFailure as exc:
            print(f"release consistency self-test failed: {exc}", file=sys.stderr)
            return 1
    if len(sys.argv) != 1:
        print("usage: check_release_consistency.py [--self-test]", file=sys.stderr)
        return 2

    try:
        passed = check_release_consistency()
    except CheckFailure as exc:
        print(f"release consistency check failed: {exc}", file=sys.stderr)
        return 1

    for item in passed:
        print(f"ok: {item}")
    print("release consistency check passed")
    return 0


